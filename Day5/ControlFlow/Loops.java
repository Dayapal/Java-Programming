public class Loops {
    public static void main(String[] args) {
        for (int i = 0; i < 5; i++) {
            System.out.println("Iteration " + i);
        }

        String[] stack = { "Mongodb", "Express", "React", "Nodejs", "MYSQL" };
        for (String tech : stack) {
            System.out.println("Tech " + tech);
        }

    }

}
