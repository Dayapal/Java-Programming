public class Operators08 {
    public static void main(String[] args){

 int a = 10;
        int b = 3;

        // Arithmetic
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);

        // Comparison
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a == b);
        System.out.println(a != b);

        // Logical
        System.out.println(a > 5 && b > 2);
        System.out.println(a > 20 || b > 2);
        System.out.println(!(a > b));

    }
}
